  await expect(page).toHaveURL(/\/medicos$/)
  await expect(page.getByText('Nenhum resultado encontrado')).toBeVisible()
  const nav = page.getByRole('navigation', { name: width < 1100 ? 'Navegação no celular' : 'Navegação principal', exact: true })
  await nav.getByRole('link', { name: 'Início', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sua rede de saúde, em um só lugar.' })).toBeVisible()
  await expect(page.getByText('Seu cuidado começa com uma boa conexão')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
