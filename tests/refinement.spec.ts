test('automatic CEP keeps manual edits and distinguishes missing CEP from service failure', async ({ page, db }) => {
  await login(page, '/estabelecimentos/novo'); await page.getByLabel('Nome do estabelecimento').fill('Endereço completo')
  await page.getByLabel('Website', { exact: true }).fill('clinica.com.br')
  await step(page, 3); await page.getByRole('button', { name: 'Adicionar endereço', exact: true }).click()
  let requests = 0
  let releaseRetry: (() => void) | undefined
  await page.route('https://viacep.com.br/**', async route => {
    requests++
    if (requests === 2) await new Promise<void>(resolve => { releaseRetry = resolve })
    return route.fulfill({ json: { logradouro: 'Rua do CEP', bairro: 'Centro', localidade: 'Belém', uf: 'PA' } })
  })
  await page.getByLabel('CEP 1', { exact: true }).pressSequentially('66055030')
  await expect(page.getByLabel('CEP 1', { exact: true })).toHaveValue('66055-030')
  await expect(page.getByLabel('Cidade 1')).toHaveValue('Belém')
  await page.getByLabel('Logradouro 1').fill('Rua corrigida manualmente')
  const retryRequest = page.waitForRequest('https://viacep.com.br/**')
  await page.getByRole('button', { name: 'Consultar CEP', exact: true }).click()
  await retryRequest
  await expect(page.getByText('Consultando CEP…', { exact: true })).toBeVisible()
  await page.getByLabel('Logradouro 1').fill('Minha correção durante a consulta')
  releaseRetry?.()
  await expect(page.getByText('CEP consultado. Confira o endereço e complete o número.', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Logradouro 1')).toHaveValue('Minha correção durante a consulta')
  await page.route('https://viacep.com.br/**', route => route.fulfill({ json: { erro: true } }))
  await page.getByLabel('CEP 1', { exact: true }).fill('66055031')
  await expect(page.getByText(/CEP não encontrado/)).toBeVisible()
  await page.route('https://viacep.com.br/**', route => route.fulfill({ status: 503, json: {} }))
  await page.getByLabel('CEP 1', { exact: true }).fill('66055032')
  await expect(page.getByText(/Consulta indisponível/)).toBeVisible()
  await page.getByRole('button', { name: 'Salvar estabelecimento', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Endereço completo', exact: true })).toBeVisible()
  await expect(page.getByText('CEP 66055-032', { exact: true })).toBeVisible()
  expect((await db.query('select website from public.establishments')).rows[0]).toEqual({ website: 'https://clinica.com.br/' })
  expect((await db.query('select postal_code,street from public.addresses')).rows[0]).toEqual({ postal_code: '66055032', street: 'Minha correção durante a consulta' })
})

