import {expect} from '@playwright/test'
import {test,login,noOverflow} from './fixtures/network'
import {seedExplorer} from '../scripts/network-explorer-fixture.mjs'

test.use({hasTouch:true})
for(const width of [360,390])test(`touch selection, scrolling and applying at ${width}px`,async({page,db})=>{
  await seedExplorer(db)
  await page.setViewportSize({width,height:780})
  await login(page,'/cadastros')
  await page.getByRole('button',{name:/^Filtros/}).tap()
  const dialog=page.getByRole('dialog',{name:'Filtrar minha rede',exact:true})
  await dialog.getByRole('combobox',{name:'Especialidade',exact:true}).tap()
  await page.getByRole('combobox',{name:'Pesquisar Especialidade',exact:true}).fill('cardio')
  const specialty=page.getByRole('option',{name:'Cardiologia',exact:true})
  await expect(specialty).toHaveAttribute('aria-disabled','false')
  await specialty.tap()
  await expect(dialog.getByRole('combobox',{name:'Especialidade',exact:true})).toContainText('Cardiologia')
  await dialog.getByRole('combobox',{name:'Cidade',exact:true}).tap()
  await page.getByRole('combobox',{name:'Pesquisar Cidade',exact:true}).fill('Belem')
  const city=page.getByRole('option',{name:'Belém',exact:true})
  await expect(city).toHaveAttribute('aria-disabled','false')
  await city.tap()
  await dialog.getByRole('combobox',{name:'Estado (UF)',exact:true}).tap()
  await page.getByRole('option',{name:'Todos os estados',exact:true}).tap()
  await expect(dialog.getByRole('combobox',{name:'Cidade',exact:true})).toContainText('Belém')
  await dialog.getByRole('combobox',{name:'Status',exact:true}).tap()
  await page.getByRole('option',{name:'Ativo',exact:true}).tap()
  await expect(dialog.getByRole('combobox',{name:'Status',exact:true})).toContainText('Ativo')
  expect(await dialog.locator('.filter-scroll').evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
  await dialog.getByRole('button',{name:'Aplicar filtros'}).tap()
  await expect(page).toHaveURL(/specialty=/)
  expect(new URL(page.url()).searchParams.get('active')).toBe('true')
  await noOverflow(page)
})
