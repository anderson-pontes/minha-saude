test('an invalid agenda response affects only its dashboard section',async({page,db})=>{
 await call(db,'agenda_preferences',[],'')
 let requests=0
 const errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/rpc/agenda_upcoming',route=>{requests++;return route.fulfill({json:{}})})
 await login(page,'/')
 await expect(page.getByRole('heading',{name:'Sua rede de saúde, em um só lugar.',exact:true})).toBeVisible()
 await expect(page.getByRole('region',{name:'Próximos compromissos',exact:true}).getByRole('alert')).toContainText('Não foi possível carregar sua agenda.')
 expect(requests).toBe(1)
 expect(errors).toEqual([])
})

