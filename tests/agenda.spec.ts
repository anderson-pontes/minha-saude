test('push permission is requested only by explicit action and denial preserves internal reminders',async({page,db})=>{
 await call(db,'agenda_preferences',[],'')
 await page.addInitScript(()=>{
  Reflect.set(window,'pushPermissionCalls',0)
  Object.defineProperty(Notification,'permission',{get:()=> 'default'})
  Notification.requestPermission=async()=>{Reflect.set(window,'pushPermissionCalls',Number(Reflect.get(window,'pushPermissionCalls'))+1);return 'denied'}
 })
 await login(page,'/agenda')
 expect(await page.evaluate(()=>Reflect.get(window,'pushPermissionCalls'))).toBe(0)
 await page.getByRole('button',{name:'Preferências',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Preferências da agenda',exact:true})
 await dialog.getByRole('button',{name:'Ativar lembretes de consultas e exames',exact:true}).click()
 await expect(dialog.getByRole('alert')).toContainText('Permissão negada')
 expect(await page.evaluate(()=>Reflect.get(window,'pushPermissionCalls'))).toBe(1)
 await expect(dialog.getByRole('checkbox',{name:'Receber lembretes de consultas e exames',exact:true})).toBeChecked()
})

