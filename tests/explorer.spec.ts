import {expect} from '@playwright/test'
import {test,login,noOverflow} from './fixtures/network'
import {seedExplorer} from '../scripts/network-explorer-fixture.mjs'

for(const width of [390,768,1440])test(`plan overview and paginated relationships at ${width}px`,async({page,db})=>{
  const {plan}=await seedExplorer(db)
  await page.setViewportSize({width,height:900})
  const requests:{fn:string;status:number}[]=[]
  page.on('response',r=>{if(r.url().includes('/rpc/'))requests.push({fn:r.url().split('/rpc/')[1],status:r.status()})})
  await login(page,'/convenios')
  const card=page.locator('.plan-card');await expect(card).toHaveCount(1)
  await expect(card).toContainText('47971/018-8');await expect(card).toContainText('35')
  await expect(card).not.toContainText('Clínica 01')
  expect((await card.boundingBox())!.height).toBeLessThan(440)
  await expect(page.getByRole('link',{name:'Novo convênio'})).toHaveCount(1)
  await noOverflow(page)
  await page.screenshot({path:`test-results/explorer-plans-${width}.png`,fullPage:true})
  await page.getByRole('button',{name:'Tabela',exact:true}).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.locator('tbody')).not.toContainText('Clínica 01')
  await noOverflow(page)
  await page.getByRole('button',{name:'Cards',exact:true}).click()
  await page.getByRole('link',{name:'Ver rede credenciada'}).click()
  await expect(page).toHaveURL(new RegExp(`/convenios/${plan}`))
  await expect(page.locator('.plan-overview-metrics')).toContainText('35')
  await expect(page.locator('.network-grid .entity-card')).toHaveCount(12)
  expect(await page.locator('.network-grid').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(width===1440?3:width===768?2:1)
  await expect(page.getByRole('heading',{name:'Clínica 01',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Próxima',exact:true}).click()
  await expect(page.getByText('Página 2 de 3')).toBeVisible()
  await expect(page.getByRole('heading',{name:'Clínica 13',exact:true})).toBeVisible()
  await page.getByRole('tab',{name:'Profissionais',exact:true}).click()
  await expect(page.locator('.network-grid .entity-card')).toHaveCount(12)
  await expect(page.locator('.network-grid')).not.toContainText('Consultório particular')
  await noOverflow(page)
  await page.screenshot({path:`test-results/explorer-professionals-${width}.png`,fullPage:true})
  await page.getByRole('tab',{name:'Especialidades',exact:true}).click()
  await expect(page.locator('.specialty-network-card')).toHaveCount(1)
  await expect(page.locator('.specialty-network-card')).toContainText('Cardiologia')
  await page.getByRole('button',{name:'Ver estabelecimentos',exact:true}).click()
  await expect(page.getByRole('combobox',{name:'Especialidade',exact:true})).toHaveValue('Cardiologia')
  await expect(page.locator('.network-grid .entity-card')).toHaveCount(12)
  await page.getByRole('combobox',{name:'Cidade',exact:true}).fill('ana')
  await page.getByRole('option',{name:'Ananindeua',exact:true}).click()
  await expect(page.getByText('17 vínculos encontrados',{exact:true})).toBeVisible()
  await page.getByRole('combobox',{name:'Tipo',exact:true}).selectOption('clinic')
  await expect(page.getByText('Nenhum vínculo encontrado',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Limpar filtros da rede'}).click()
  await expect(page.getByRole('combobox',{name:'Cidade',exact:true})).toHaveValue('')
  await page.getByRole('textbox',{name:'Buscar na rede credenciada'}).fill('Clínica 35')
  await page.getByRole('button',{name:'Buscar',exact:true}).click()
  await expect(page.locator('.network-grid .entity-card')).toHaveCount(1)
  await noOverflow(page)
  expect(requests.filter(r=>r.status!==200)).toEqual([])
  expect(requests.filter(r=>r.fn==='network_document'||r.fn==='search_network')).toEqual([])
})

test('professional cards bound large relationships and keep deletion behind confirmation',async({page,db})=>{
  const fixture=await seedExplorer(db)
  for(let n=1;n<=3;n++) {
    const s=(await db.query<{id:string}>('insert into public.specialties(name) values($1) returning id',[`Especialidade adicional ${n}`])).rows[0].id
    const e=(await db.query<{id:string}>("insert into public.establishments(name,kind) values($1,'clinic') returning id",[`Outro estabelecimento ${n}`])).rows[0].id
    await db.query('insert into public.doctor_specialties(doctor_id,specialty_id) values($1,$2)',[fixture.doctors[0],s])
    await db.query('insert into public.doctor_establishments(doctor_id,establishment_id) values($1,$2)',[fixture.doctors[0],e])
  }
  await login(page,'/medicos?q=Profissional%2001')
  const card=page.locator('.compact-provider-card');await expect(card).toHaveCount(1)
  await expect(card.getByRole('link',{name:'+3 especialidades',exact:true})).toBeVisible()
  await expect(card.getByRole('link',{name:'+4 estabelecimentos',exact:true})).toBeVisible()
  await expect(card.getByRole('link',{name:'Editar',exact:true})).not.toBeVisible()
  await expect(card.locator('summary')).toHaveAccessibleName('Mais opções para Profissional 01')
  await card.getByRole('button',{name:'Favoritar',exact:true}).click()
  await expect(card.getByRole('button',{name:'Desfavoritar',exact:true})).toBeVisible()
  await card.locator('summary').click();await card.getByRole('button',{name:'Excluir',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Excluir cadastro?'})).toBeVisible()
  await page.getByRole('button',{name:'Cancelar',exact:true}).click()
  expect((await db.query('select id from public.doctors where id=$1',[fixture.doctors[0]])).rows.length).toBe(1)
})

for(const width of [390,1440])test(`filters are drafts, keyboard searchable and dependent at ${width}px`,async({page,db})=>{
  await seedExplorer(db);await page.setViewportSize({width,height:900})
  await login(page,'/cadastros')
  const filterButton=page.getByRole('button',{name:/^Filtros/});await filterButton.click()
  const dialog=page.getByRole('dialog',{name:'Filtrar minha rede'})
  await expect(dialog).toBeVisible()
  expect(await page.evaluate(()=>document.body.style.overflow)).toBe('hidden')
  await dialog.getByRole('combobox',{name:'Especialidade',exact:true}).fill('cardio')
  await page.getByRole('option',{name:'Cardiologia',exact:true}).waitFor()
  await dialog.getByRole('combobox',{name:'Especialidade',exact:true}).press('ArrowDown')
  await dialog.getByRole('combobox',{name:'Especialidade',exact:true}).press('Enter')
  await expect(dialog.getByRole('combobox',{name:'Especialidade',exact:true})).toHaveValue('Cardiologia')
  expect(new URL(page.url()).searchParams.has('specialty')).toBe(false)
  await dialog.getByRole('combobox',{name:'Cidade',exact:true}).fill('Belém')
  await page.getByRole('option',{name:'Belém',exact:true}).click()
  await dialog.getByRole('combobox',{name:'Estado (UF)',exact:true}).fill('SP')
  await page.getByRole('option',{name:'SP',exact:true}).click()
  await expect(dialog.getByRole('status').filter({hasText:'Cidade e bairro foram limpos'})).toBeVisible()
  await expect(dialog.getByRole('combobox',{name:'Cidade',exact:true})).toHaveValue('')
  await noOverflow(page)
  await page.screenshot({path:`test-results/explorer-filters-${width}.png`,fullPage:true})
  await dialog.getByRole('button',{name:'Aplicar filtros'}).click()
  await expect(dialog).not.toBeVisible()
  await expect(page).toHaveURL(/specialty=/)
  expect(await page.evaluate(()=>document.body.style.overflow)).not.toBe('hidden')
  await expect(page.locator('.applied-filters')).toContainText('Cardiologia')
  await filterButton.click()
  await expect(dialog.getByRole('combobox',{name:'Especialidade',exact:true})).toHaveValue('Cardiologia')
  await dialog.getByRole('button',{name:'Limpar Especialidade',exact:true}).click()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(filterButton).toBeFocused()
  await expect(page).toHaveURL(/specialty=/)
  await page.getByRole('button',{name:'Remover filtro Especialidade',exact:true}).click()
  await expect(page).not.toHaveURL(/specialty=/)
  await filterButton.click();await dialog.getByRole('button',{name:'Limpar filtros',exact:true}).click()
  await dialog.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
  await expect(page).not.toHaveURL(/state=/)
})
