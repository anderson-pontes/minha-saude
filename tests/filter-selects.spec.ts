import { expect } from '@playwright/test'
import { test, login, noOverflow } from './fixtures/network'
import { seedExplorer } from '../scripts/network-explorer-fixture.mjs'

for (const width of [360,390,768,1024,1440,1920]) test(`floating filters preserve layout, focus and drafts at ${width}px`, async ({page,db}) => {
  test.setTimeout(60000)
  await seedExplorer(db)
  await page.setViewportSize({width,height:900})
  await login(page,'/cadastros')
  const opener=page.getByRole('button',{name:/^Filtros/})
  await opener.click()
  const dialog=page.getByRole('dialog',{name:'Filtrar minha rede',exact:true})
  expect(await dialog.locator('select').count()).toBe(0)
  for(const label of ['Tipo de estabelecimento','Especialidade','Médico/profissional','Convênio','Estado (UF)','Cidade','Bairro','Status']) {
    const trigger=dialog.getByRole('combobox',{name:label,exact:true})
    await trigger.scrollIntoViewIfNeeded()
    const before=await dialog.evaluate(el=>({height:el.getBoundingClientRect().height,scroll:el.querySelector('.filter-scroll')!.scrollHeight}))
    const bounds=(await trigger.boundingBox())!
    if(label==='Especialidade')await trigger.press('ArrowDown')
    else await trigger.click()
    const popup=page.locator('.filter-select-popup')
    await expect(popup).toBeVisible()
    const box=(await popup.boundingBox())!
    expect(box.width).toBeCloseTo(bounds.width,0)
    expect(box.y).toBeGreaterThanOrEqual(0)
    expect(box.y+box.height).toBeLessThanOrEqual(901)
    expect(await popup.evaluate(el=>!!el.closest('dialog'))).toBe(true)
    expect(await dialog.evaluate(el=>({height:el.getBoundingClientRect().height,scroll:el.querySelector('.filter-scroll')!.scrollHeight}))).toEqual(before)
    expect(bounds.height).toBe(44)
    if(label==='Médico/profissional') {
      await expect(page.getByRole('option',{name:'Profissional 01',exact:true})).toHaveAttribute('aria-disabled','false')
      expect(await popup.locator('.filter-select-options').evaluate(el=>el.scrollHeight>el.clientHeight)).toBe(true)
      await page.screenshot({path:`test-results/floating-professionals-${width}.png`,animations:'disabled'})
    }
    await page.keyboard.press('Escape')
    await expect(popup).toHaveCount(0)
    await expect(dialog).toBeVisible()
    await expect(trigger).toBeFocused()
  }
  await dialog.getByRole('combobox',{name:'Especialidade',exact:true}).click()
  const search=page.getByRole('combobox',{name:'Pesquisar Especialidade',exact:true})
  await expect(search).toBeFocused()
  await search.fill('cardio')
  await expect(page.getByRole('option',{name:'Cardiologia',exact:true})).toHaveAttribute('aria-disabled','false')
  await search.press('ArrowDown');await search.press('Enter')
  await expect(dialog.getByRole('combobox',{name:'Especialidade',exact:true})).toContainText('Cardiologia')
  await dialog.getByRole('button',{name:'Aplicar filtros'}).click()
  await expect(page).toHaveURL(/specialty=/)
  await opener.click()
  await expect(dialog.getByRole('combobox',{name:'Especialidade',exact:true})).toContainText('Cardiologia')
  await dialog.getByRole('combobox',{name:'Cidade',exact:true}).click()
  await page.getByRole('combobox',{name:'Pesquisar Cidade',exact:true}).fill('zzzzzz')
  await expect(page.getByText('Nenhuma opção encontrada',{exact:true})).toBeVisible()
  await dialog.getByRole('heading',{name:'Filtrar minha rede',exact:true}).click()
  await expect(page.locator('.filter-select-popup')).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button',{name:'Limpar filtros',exact:true}).click()
  await dialog.getByRole('button',{name:'Aplicar filtros'}).click()
  await expect(page).not.toHaveURL(/specialty=/)
  await noOverflow(page)
})

test('long dropdown flips above its trigger on a short mobile viewport',async({page,db})=>{
  await seedExplorer(db)
  await page.setViewportSize({width:390,height:560})
  await login(page,'/cadastros')
  await page.getByRole('button',{name:/^Filtros/}).click()
  const dialog=page.getByRole('dialog',{name:'Filtrar minha rede',exact:true})
  const trigger=dialog.getByRole('combobox',{name:'Médico/profissional',exact:true})
  await trigger.click()
  const popup=page.locator('.filter-select-popup')
  await expect(page.getByRole('option',{name:'Profissional 01',exact:true})).toHaveAttribute('aria-disabled','false')
  await expect(popup).toHaveAttribute('data-side','top')
  expect((await popup.boundingBox())!.y+(await popup.boundingBox())!.height).toBeLessThan((await trigger.boundingBox())!.y)
  await page.screenshot({path:'test-results/floating-flip-mobile.png',animations:'disabled'})
  await page.getByRole('combobox',{name:'Pesquisar Médico/profissional',exact:true}).press('End')
  await page.getByRole('combobox',{name:'Pesquisar Médico/profissional',exact:true}).press('Enter')
  await expect(popup).toHaveCount(0)
  await expect(trigger).toContainText('Profissional')
})

test('lookup errors show a retry and recover without closing the dialog',async({page,db})=>{
  await seedExplorer(db)
  let failing=true
  await page.route('**/rpc/network_lookup',route=>{
    const body=route.request().postDataJSON()
    if(failing&&body.p_category==='specialties')return route.fulfill({status:403,json:{code:'42501',message:'Controlled lookup failure'}})
    return route.fallback()
  })
  await login(page,'/cadastros')
  await page.getByRole('button',{name:/^Filtros/}).click()
  const dialog=page.getByRole('dialog',{name:'Filtrar minha rede',exact:true})
  await dialog.getByRole('combobox',{name:'Especialidade',exact:true}).click()
  const retry=page.getByRole('button',{name:'Falha ao buscar. Tentar novamente',exact:true})
  await expect(retry).toBeVisible()
  await expect(dialog).toBeVisible()
  failing=false
  await retry.click()
  await expect(page.getByRole('option',{name:'Cardiologia',exact:true})).toHaveAttribute('aria-disabled','false')
  await page.getByRole('option',{name:'Cardiologia',exact:true}).click()
  await expect(dialog.getByRole('combobox',{name:'Especialidade',exact:true})).toContainText('Cardiologia')
})
