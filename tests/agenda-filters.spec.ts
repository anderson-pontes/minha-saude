 await expect(popup.getByRole('alert')).toContainText('Não foi possível carregar mais opções.')
 expect(nextRequests).toBe(1)
 await expect(popup.getByRole('option',{name:'Local 001',exact:true})).toBeVisible()
 failing=false;await popup.getByRole('button',{name:'Tentar novamente',exact:true}).click()
