async function choose(page:Page,label:string,term:string,name:string){
 await page.getByRole('combobox',{name:label,exact:true}).click()
 await page.getByRole('combobox',{name:`Pesquisar ${label}`,exact:true}).fill(term)
 const option=page.getByRole('option',{name,exact:true})
 await expect(option).toHaveAttribute('aria-disabled','false');await option.click()
}
