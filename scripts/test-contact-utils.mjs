import assert from 'node:assert/strict'
import { formatPhone, normalizePhone, validatePhone, phoneTelLink, whatsappLink, formatCep, normalizeWebsite, validateContact, addressErrors, normalizedContactValue } from '../src/lib/contact-utils.ts'

assert.equal(formatPhone('9133334444'),'(91) 3333-4444')
assert.equal(formatPhone('91988449970'),'(91) 98844-9970')
for(const raw of ['91988449970','(91) 98844-9970','+55 (91) 98844-9970','5591988449970']){
 assert.equal(normalizePhone(raw),'91988449970');assert.equal(whatsappLink(raw),'https://wa.me/5591988449970');assert.equal(phoneTelLink(raw),'tel:+5591988449970')
}
assert.equal(normalizePhone('5533334444'),'5533334444','DDD 55 must not be mistaken for DDI')
assert.equal(formatPhone('5533334444'),'(55) 3333-4444')
assert.equal(normalizePhone('+44 20 7946 0018'),'+442079460018')
assert.equal(normalizePhone('0044 20 7946 0018'),'+442079460018')
assert.equal(whatsappLink('+44 20 7946 0018'),'https://wa.me/442079460018')
assert.equal(phoneTelLink('+1 415 555 2671'),'tel:+14155552671')
assert.equal(formatPhone('+44 20 7946 0018'),'+44 20 7946 0018')
assert.equal(validatePhone('+44 20 7946 0018','mobile'),null)
assert.equal(validatePhone('9133334444','phone'),null)
assert.equal(validatePhone('91988449970','mobile'),null)
assert(validatePhone('9198844997','mobile'))
assert(validatePhone('91988449970','phone'))
assert(validatePhone('0033334444','phone'))
assert(validatePhone('+123','mobile'))
assert(validatePhone('91988449970 ramal 1','mobile'))
assert.equal(formatPhone('1234567890123456'),'1234567890123456','Legacy values must never be truncated')
assert.equal(formatCep('66055030'),'66055-030')
assert.equal(formatCep('66055-030'),'66055-030')
assert.equal(normalizeWebsite('clinica.com.br'),'https://clinica.com.br/')
assert.equal(normalizeWebsite('https://clinica.com.br/agenda'),'https://clinica.com.br/agenda')
for(const value of ['javascript:alert(1)','ftp://clinica.com.br','//evil.example','dominio','https://user:pass@clinica.com.br'])assert.equal(normalizeWebsite(value),null)
assert.equal(validateContact({kind:'email',value:'recepcao@clinica.com.br'}),null)
assert(validateContact({kind:'email',value:'email-invalido'}))
assert.equal(normalizedContactValue({kind:'whatsapp',value:'+55 (91) 98844-9970'}),'91988449970')
assert.equal(normalizedContactValue({kind:'email',value:' recepcao@clinica.com.br '}),'recepcao@clinica.com.br')
assert(Object.values(addressErrors({street:'',city:'',state:'XX',postal_code:'6605'})).every(Boolean))
assert(Object.values(addressErrors({street:'Rua A',city:'Belém',state:'PA',postal_code:'66055-030'})).every(value=>!value))
console.log('PASS: BR and international formatting, normalization, DDI/DDD distinction, phone/email/URL/address validation, safe links, legacy compatibility and CEP formatting.')
